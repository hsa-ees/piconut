void m_membrana_hw_emem::proc_clk_ram_port_a()
{

    sc_uint<32> combData;

    while(1)
    {

        wait();

        // Port A

        if(ena.read() == 1)
        {

            if((((uint32_t(addra.read())) - ((PN_CFG_CPU_RESET_ADR) >> 2)) < 0x00) || (((uint32_t)(addra.read()) - ((PN_CFG_CPU_RESET_ADR) >> 2)) >= PN_CFG_MEMBRANA_EMEM_SIZE))
            {
                PN_ERROR("Wrong memory access!");
            }
            combData = ram[(uint32_t)(addra.read()) - (((uint32_t)(PN_CFG_CPU_RESET_ADR) >> 2))];

            // check if nucleus writes into code area
            if(wea.read() == 1)
            {
                if(addra.read() > ((uint32_t)(PN_CFG_CPU_RESET_ADR) + 0x0001FFFF))
                    PN_INFO("!!! WRITING CODE ERROR !!!");
            }

            doa = combData;

            for(uint i = 0; i < 4; i++)
            {
                if(wea.read()[i] == 1)
                {
                    combData &= ~(0xffU << (8 * i));
                    combData |= (dia.read() & (0xffU << (8 * i)));
                }
            }
            ram[(uint32_t)addra.read() - ((uint32_t)(PN_CFG_CPU_RESET_ADR) >> 2)] = combData;
        }
    }
}

void m_membrana_hw_emem::proc_clk_ram_port_b()
{

    sc_uint<32> combData;

    while(1)
    {
        wait();
        // Port B

        if(enb == 1)
        {

            combData = ram[addrb.read() - PN_CFG_CPU_RESET_ADR];
            dob = combData;

            for(uint i = 0; i < 4; i++)
            {

                if(web.read()[i] == 1)
                {
                    combData &= ~(0xffU << (8 * i));
                    combData |= (dib.read() & (0xffU << (8 * i)));
                }
            }
            ram[addra.read() - PN_CFG_CPU_RESET_ADR] = combData;
        }
    }
}

