void m_membrana_hw_emem::load_elf(const std::string& elf_file_path)
{
    if(elf_file_path.empty())
    {
        PN_WARNING("ELF file path is empty. Leaving RAM uninitielized ...");
        return;
    }

    pn_c_elf_reader elf_reader;
    elf_reader.read_file(elf_file_path.c_str());

    PN_INFOF(("ELF start address: 0x%x; ELF size: 0x%x", elf_reader.get_size(), elf_reader.get_base_addr()));

    if(elf_reader.get_size() == 0 || elf_reader.get_base_addr() == UINT32_MAX)
    {
        PN_ERROR("ELF file size or start address is zero or invalid - check ELF file and reader.");
        return;
    }

    unsigned char* memory_to_load = elf_reader.get_memory();

    size_t size = elf_reader.get_size();

    // Calculate the number of 32-bit words required
    size_t num_words = (size + 3) / 4; // Round up if not a multiple of 4

    // Fill the sc_vector with 32-bit words from memory_to_load
    for(size_t i = 0; i < num_words; ++i)
    {
        uint32_t word = 0;

        // Loop through up to 4 bytes at a time and construct a 32-bit word
        for(size_t j = 0; j < 4 && (i * 4 + j) < size; ++j)
        {
            word |= (static_cast<uint32_t>(memory_to_load[i * 4 + j]) & 0xFF) << (8 * j);
        }

        // Assign the constructed 32-bit word to the ram
        ram[i] = word;
    }

    PN_INFO("Blockram successfully initialized with ELF-File! ");
}

